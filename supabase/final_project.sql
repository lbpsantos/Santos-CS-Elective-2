-- 1. ROLES -------------------------------------------------------------
-- Exactly two roles. Every new account starts as a customer.
create table if not exists public.roles (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  role       varchar not null
);
alter table public.roles add column if not exists role varchar;
create unique index if not exists roles_role_key on public.roles (role);

insert into public.roles (role) values ('customer'), ('admin')
on conflict (role) do nothing;


-- 2. PROFILES ----------------------------------------------------------
-- One row per account. profiles.id is the same uuid as auth.users.id.
create table if not exists public.profiles (
  id         uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  email      text,
  firstname  text,
  lastname   text,
  role_id    bigint references public.roles (id)
);
alter table public.profiles add column if not exists email text;
alter table public.profiles add column if not exists firstname text;
alter table public.profiles add column if not exists lastname text;
alter table public.profiles add column if not exists role_id bigint
  references public.roles (id);


-- 3. PRODUCTS: stock column ----------------------------------------------
-- Books that exist already start with 10 copies; new books default to 0.
alter table public.products
  add column if not exists stock integer not null default 10;
update public.products set stock = 0 where stock is null;
alter table public.products alter column stock set default 0;
alter table public.products alter column stock set not null;
alter table public.products drop constraint if exists products_stock_check;
alter table public.products add constraint products_stock_check check (stock >= 0);


-- 4. ORDERS AND ORDER ITEMS --------------------------------------------
create table if not exists public.orders (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id    uuid,
  status     text not null default 'pending',
  total      numeric(10, 2) not null default 0
);
alter table public.orders add column if not exists user_id uuid;
alter table public.orders add column if not exists status text default 'pending';
alter table public.orders add column if not exists total numeric(10, 2) default 0;
update public.orders set status = 'done'
  where status is null or status not in ('pending', 'done', 'cancelled');
update public.orders set total = 0 where total is null;
alter table public.orders alter column status set not null;
alter table public.orders alter column total set not null;
alter table public.orders drop constraint if exists orders_status_check;
alter table public.orders add constraint orders_status_check
  check (status in ('pending', 'done', 'cancelled'));
create index if not exists orders_user_id_idx on public.orders (user_id);

-- Each item keeps a snapshot of the book's name and the price paid, so
-- old orders stay correct when a book's price changes or it is deleted.
create table if not exists public.order_items (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  order_id     bigint not null references public.orders (id) on delete cascade,
  product_id   bigint,
  product_name text not null default '',
  unit_price   numeric(10, 2) not null default 0,
  quantity     integer not null default 1
);
alter table public.order_items add column if not exists product_id bigint;
alter table public.order_items add column if not exists product_name text not null default '';
alter table public.order_items add column if not exists unit_price numeric(10, 2) not null default 0;
alter table public.order_items add column if not exists quantity integer not null default 1;
alter table public.order_items alter column product_id drop not null;
create index if not exists order_items_order_id_idx on public.order_items (order_id);

-- The links between the tables. Old links made in the Table Editor are
-- replaced so that:
-- - orders.user_id points to profiles (the app reads the customer's name),
-- - deleting a book keeps old orders (order_items.product_id becomes null;
--   the name and price snapshot stay).
do $$
declare
  fk record;
begin
  for fk in
    select c.conname, c.conrelid::regclass as tbl
    from pg_constraint c
    join pg_attribute a on a.attrelid = c.conrelid and a.attnum = any (c.conkey)
    where c.contype = 'f'
      and ((c.conrelid = 'public.orders'::regclass and a.attname = 'user_id')
        or (c.conrelid = 'public.order_items'::regclass and a.attname = 'product_id'))
  loop
    execute format('alter table %s drop constraint %I', fk.tbl, fk.conname);
  end loop;
end $$;

alter table public.orders
  add constraint orders_user_id_fkey
  foreign key (user_id) references public.profiles (id) on delete cascade;
alter table public.order_items
  add constraint order_items_product_id_fkey
  foreign key (product_id) references public.products (id) on delete set null;


-- 5. FUNCTIONS ---------------------------------------------------------

-- handle_new_user: runs every time a row is added to auth.users (email
-- sign up or a Google login) and makes the matching profile as a customer.
-- Email sign up sends firstname / lastname in the user metadata; Google
-- sends given_name / family_name / full_name instead.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  meta       jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  full_name  text  := trim(coalesce(meta->>'full_name', meta->>'name', ''));
  first_word text  := split_part(full_name, ' ', 1);
begin
  insert into public.profiles (id, email, firstname, lastname, role_id)
  values (
    new.id,
    new.email,
    coalesce(meta->>'firstname', meta->>'given_name', nullif(first_word, '')),
    coalesce(
      meta->>'lastname',
      meta->>'family_name',
      nullif(trim(substr(full_name, length(first_word) + 1)), '')
    ),
    (select id from public.roles where role = 'customer')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Accounts made before this file was run get a profile too.
insert into public.profiles (id, email, firstname, lastname, role_id)
select
  u.id,
  u.email,
  coalesce(u.raw_user_meta_data->>'firstname', u.raw_user_meta_data->>'given_name',
           nullif(split_part(coalesce(u.raw_user_meta_data->>'full_name',
                                      u.raw_user_meta_data->>'name', ''), ' ', 1), '')),
  coalesce(u.raw_user_meta_data->>'lastname', u.raw_user_meta_data->>'family_name'),
  (select id from public.roles where role = 'customer')
from auth.users u
where not exists (select 1 from public.profiles p where p.id = u.id);

-- Profiles without a role (made in the Table Editor) become customers.
update public.profiles
set role_id = (select id from public.roles where role = 'customer')
where role_id is null;

-- is_admin: true when the logged-in user's profile has the admin role.
-- The RLS policies below call it.
--
-- "security definer" makes it run with the rights of the function's owner,
-- skipping RLS on the profiles table. Without it, the "admins read all
-- profiles" policy would call is_admin(), which reads profiles, which runs
-- the policy again... and Postgres stops with "infinite recursion".
create or replace function public.is_admin()
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  return exists (
    select 1
    from public.profiles p
    join public.roles r on r.id = p.role_id
    where p.id = auth.uid() and r.role = 'admin'
  );
end;
$$;

-- place_order([{product_id, quantity}, ...]) is the ONLY way to make an
-- order. The app sends just the ids and quantities; the names, prices and
-- stock checks all come from the products table at this moment, never
-- from the app. A function runs as one transaction: if anything fails
-- (e.g. a book has too little stock), every change is rolled back and
-- nothing is saved. It returns the new order with its items as JSON.
create or replace function public.place_order(items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  customer    uuid := auth.uid();
  item        jsonb;
  book        record;
  wanted      integer;
  new_order   public.orders;
  order_total numeric(10, 2) := 0;
  result      jsonb;
begin
  if customer is null then
    raise exception 'You must be logged in to place an order.'
      using errcode = '42501';
  end if;
  if public.is_admin() then
    raise exception 'Admin accounts cannot place orders.'
      using errcode = '42501';
  end if;
  if items is null or jsonb_typeof(items) <> 'array'
     or jsonb_array_length(items) = 0 then
    raise exception 'Your cart is empty.';
  end if;

  -- 1. Save the order first, as "pending", to get its id.
  insert into public.orders (user_id, status, total)
  values (customer, 'pending', 0)
  returning * into new_order;

  -- 2. One order_items row per cart item, read from the products table.
  for item in select * from jsonb_array_elements(items) loop
    wanted := (item->>'quantity')::integer;
    if wanted is null or wanted < 1 then
      raise exception 'Quantity must be at least 1.';
    end if;

    -- "for update" locks the book's row until the order is finished, so
    -- two customers can't both buy the last copy at the same time.
    select id, name, price, stock into book
    from public.products
    where id = (item->>'product_id')::bigint
    for update;
    if not found then
      raise exception 'A book in your cart is no longer available.';
    end if;
    if book.stock < wanted then
      raise exception 'Only % left in stock for "%".', book.stock, book.name;
    end if;

    insert into public.order_items
      (order_id, product_id, product_name, unit_price, quantity)
    values (new_order.id, book.id, book.name, book.price, wanted);

    -- 3. Stock goes down in the same transaction.
    update public.products set stock = stock - wanted where id = book.id;

    order_total := order_total + book.price * wanted;
  end loop;

  -- 4. Everything worked: save the total and set the status to done.
  update public.orders
  set total = order_total, status = 'done'
  where id = new_order.id
  returning * into new_order;

  select to_jsonb(new_order) || jsonb_build_object(
    'order_items',
    (select coalesce(jsonb_agg(to_jsonb(i) order by i.id), '[]'::jsonb)
     from public.order_items i where i.order_id = new_order.id)
  ) into result;
  return result;
end;
$$;

revoke execute on function public.place_order(jsonb) from public, anon;
grant execute on function public.place_order(jsonb) to authenticated;


-- 6. ROW LEVEL SECURITY --------------------------------------------------
-- Hiding a button in the app is NOT security: anyone with the public anon
-- key can send their own requests to Supabase. These policies are what
-- really stops a customer from adding a book or reading another customer's
-- orders. Signed-out requests (the anon role) get no access at all.

-- Start clean: remove every old policy on these tables (including ones
-- made in the dashboard), so only the policies below are left.
do $$
declare
  pol record;
begin
  for pol in
    select policyname, tablename from pg_policies
    where schemaname = 'public'
      and tablename in ('roles', 'profiles', 'genres', 'products', 'orders', 'order_items')
  loop
    execute format('drop policy %I on public.%I', pol.policyname, pol.tablename);
  end loop;
end $$;

alter table public.roles       enable row level security;
alter table public.profiles    enable row level security;
alter table public.genres      enable row level security;
alter table public.products    enable row level security;
alter table public.orders      enable row level security;
alter table public.order_items enable row level security;

revoke all on public.roles, public.profiles, public.genres, public.products,
  public.orders, public.order_items from anon, authenticated;

-- roles: customers and admins read.
grant select on public.roles to authenticated;
create policy "roles read" on public.roles
  for select to authenticated using (true);

-- profiles: read and update own row (never the role); admins read all.
grant select on public.profiles to authenticated;
-- A column grant: only these two columns can ever be changed from the app,
-- so the role can't be changed no matter what request is sent.
grant update (firstname, lastname) on public.profiles to authenticated;
create policy "profiles read own or admin" on public.profiles
  for select to authenticated
  using (id = auth.uid() or public.is_admin());
create policy "profiles update own" on public.profiles
  for update to authenticated
  using (id = auth.uid())
  with check (id = auth.uid());

-- genres (categories): customers read; admins read, add, edit, delete.
grant select, insert, update, delete on public.genres to authenticated;
create policy "genres read" on public.genres
  for select to authenticated using (true);
create policy "genres admin insert" on public.genres
  for insert to authenticated with check (public.is_admin());
create policy "genres admin update" on public.genres
  for update to authenticated
  using (public.is_admin()) with check (public.is_admin());
create policy "genres admin delete" on public.genres
  for delete to authenticated using (public.is_admin());

-- products: customers read; admins read, add, edit, delete.
grant select, insert, update, delete on public.products to authenticated;
create policy "products read" on public.products
  for select to authenticated using (true);
create policy "create product" on public.products
  for insert to authenticated with check (public.is_admin());
create policy "update product" on public.products
  for update to authenticated
  using (public.is_admin()) with check (public.is_admin());
create policy "delete product" on public.products
  for delete to authenticated using (public.is_admin());

-- orders: customers read their own; admins read all and update the status.
-- No insert grant: orders are only made by place_order() above.
grant select on public.orders to authenticated;
grant update (status) on public.orders to authenticated;
create policy "orders read own or admin" on public.orders
  for select to authenticated
  using (user_id = auth.uid() or public.is_admin());
create policy "orders admin update status" on public.orders
  for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- order_items: customers read the items of their own orders; admins all.
grant select on public.order_items to authenticated;
create policy "order_items read own or admin" on public.order_items
  for select to authenticated
  using (
    public.is_admin()
    or order_id in (select id from public.orders where user_id = auth.uid())
  );


-- 7. STORAGE (book covers) ---------------------------------------------
-- A public bucket: a cover can be shown from its link, but only admins can
-- upload, replace or delete one.
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do update set public = true;

drop policy if exists "product images read" on storage.objects;
create policy "product images read" on storage.objects
  for select using (bucket_id = 'product-images');
drop policy if exists "product images admin insert" on storage.objects;
create policy "product images admin insert" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'product-images' and public.is_admin());
drop policy if exists "product images admin update" on storage.objects;
create policy "product images admin update" on storage.objects
  for update to authenticated
  using (bucket_id = 'product-images' and public.is_admin());
drop policy if exists "product images admin delete" on storage.objects;
create policy "product images admin delete" on storage.objects
  for delete to authenticated
  using (bucket_id = 'product-images' and public.is_admin());


