-- =====================================================================
-- Shop App: the genres and products tables
-- (Price Filter + Pagination activity)
--
-- How to use: Supabase Dashboard -> SQL Editor -> New query -> paste this
-- whole file -> Run.
-- It is safe to run more than once: nothing is created twice. It also
-- updates a products table made by the first version of this file (which
-- stored the genre as text) so it uses the genres table instead.
-- =====================================================================


-- 1. GENRES ------------------------------------------------------------
-- Each book has one genre, and the app can filter the books by genre.
create table if not exists public.genres (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now()
);

-- If the genres table already existed without a name, add one.
alter table public.genres add column if not exists name text;

-- Genres that have no name yet get "Genre <id>", so nothing is lost.
-- Rename or delete them in the Table Editor if you don't need them.
update public.genres set name = 'Genre ' || id
where name is null or trim(name) = '';

alter table public.genres alter column name set not null;
create unique index if not exists genres_name_key on public.genres (name);

-- The app only reads genres. Add or rename genres in the Table Editor.
alter table public.genres enable row level security;

grant select on public.genres to anon, authenticated;

drop policy if exists "Anyone can view genres" on public.genres;
create policy "Anyone can view genres"
  on public.genres for select
  to anon, authenticated
  using (true);

insert into public.genres (name) values
  ('Adventure'), ('Epic'), ('Fairy Tales'), ('Guide'),
  ('Magic'), ('Mystery'), ('Play')
on conflict (name) do nothing;


-- 2. PRODUCTS ----------------------------------------------------------
-- The columns match lib/models/product.dart.
create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  name        text not null check (char_length(trim(name)) > 0),
  author      text not null,
  price       numeric(10, 2) not null check (price >= 0),
  description text not null default '',
  image_url   text,  -- a web link or a lib/assets/... path; null = no cover
  -- The book's genre. If the genre is deleted, the book just has no genre.
  genre_id    bigint references public.genres (id) on delete set null,
  rating      numeric(2, 1) not null default 0 check (rating between 0 and 5)
);

-- For a products table made by the first version of this file:
-- add the genre_id column...
alter table public.products
  add column if not exists genre_id bigint
  references public.genres (id) on delete set null;

-- ...and move the old "genre" text over to genre_id. The part after the
-- "/" becomes the genre, e.g. 'Fantasy / Magic' -> 'Magic'. Then the old
-- text column is removed.
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name = 'products'
      and column_name = 'genre'
  ) then
    insert into public.genres (name)
    select distinct trim(coalesce(nullif(split_part(genre, '/', 2), ''), genre))
    from public.products
    where trim(genre) <> ''
    on conflict (name) do nothing;

    update public.products p
    set genre_id = g.id
    from public.genres g
    where p.genre_id is null
      and g.name = trim(coalesce(nullif(split_part(p.genre, '/', 2), ''), p.genre));

    alter table public.products drop column genre;
  end if;
end $$;

-- Makes the price slider and genre filters faster.
create index if not exists products_price_idx on public.products (price);
create index if not exists products_genre_id_idx on public.products (genre_id);

-- Row Level Security (RLS).
-- The app has no login, so the public anon key has to be allowed to read,
-- add, edit and delete books. That is fine for this class activity. A real
-- shop would only let signed-in admins change the products.
alter table public.products enable row level security;

grant select, insert, update, delete on public.products to anon, authenticated;

drop policy if exists "Anyone can view products" on public.products;
create policy "Anyone can view products"
  on public.products for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can add products" on public.products;
create policy "Anyone can add products"
  on public.products for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Anyone can update products" on public.products;
create policy "Anyone can update products"
  on public.products for update
  to anon, authenticated
  using (true)
  with check (true);

drop policy if exists "Anyone can delete products" on public.products;
create policy "Anyone can delete products"
  on public.products for delete
  to anon, authenticated
  using (true);


